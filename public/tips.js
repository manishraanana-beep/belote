// Tirage sans répétition rapprochée : les 30 dernières astuces vues ne reviennent pas.
export function nextTip(store = globalThis.localStorage) {
  let seen = [];
  try {
    seen = JSON.parse(store?.getItem("tipsSeen") ?? "[]");
  } catch {}
  const pool = TIPS.map((_, i) => i).filter((i) => !seen.includes(i));
  const i = pool[Math.floor(Math.random() * pool.length)] ?? 0;
  try {
    store?.setItem("tipsSeen", JSON.stringify([...seen, i].slice(-30)));
  } catch {}
  return { category: TIP_CATEGORIES[TIPS[i][0]], text: TIPS[i][1] };
}
